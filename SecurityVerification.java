public class SecurityVerification {
    private int verificationId;
    private int empId;
    private String empName;
    private String degreeStatus;
    private String backgroundStatus;
    private String trainingStatus;
    private String overallEligibility;

    public int getVerificationId() { return verificationId; }
    public void setVerificationId(int verificationId) { this.verificationId = verificationId; }

    public int getEmpId() { return empId; }
    public void setEmpId(int empId) { this.empId = empId; }

    public String getEmpName() { return empName; }
    public void setEmpName(String empName) { this.empName = empName; }

    public String getDegreeStatus() { return degreeStatus; }
    public void setDegreeStatus(String degreeStatus) { this.degreeStatus = degreeStatus; }

    public String getBackgroundStatus() { return backgroundStatus; }
    public void setBackgroundStatus(String backgroundStatus) { this.backgroundStatus = backgroundStatus; }

    public String getTrainingStatus() { return trainingStatus; }
    public void setTrainingStatus(String trainingStatus) { this.trainingStatus = trainingStatus; }

    public String getOverallEligibility() { return overallEligibility; }
    public void setOverallEligibility(String overallEligibility) { this.overallEligibility = overallEligibility; }
}